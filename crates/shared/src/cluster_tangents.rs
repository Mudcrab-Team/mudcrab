//! Generated tangent data and proof over the exact encoded MCL leaf geometry.
use crate::cluster::{MclView, NO_GROUP, decode_oct_snorm16, decode_uv_unorm16};

/// Generate Bevy-compatible handed tangents and require genuine output for every
/// leaf triangle corner. Parent-only vertices are not visited. Callers initialize
/// any vertex slots they need; repeated leaf vertices receive the last corner,
/// matching Bevy's indexed-mesh generation. No default tangent is valid proof.
///
/// The producer can discard vectors while checking the same proof that runtime
/// uses when retaining packed upload words. Authored tangent streams are handled
/// by callers and never regenerated by this function.
pub fn generate_mcl_tangents(view: &MclView<'_>, set: impl FnMut(usize, [f32; 4])) -> bool {
    let mut indices = Vec::new();
    for index in 0..view.cluster_count as usize {
        let cluster = view.cluster(index);
        if cluster.refined_group == NO_GROUP {
            for local in view.cluster_triangles(&cluster) {
                indices.push(
                    view.cluster_vertex(cluster.vertex_offset as usize + *local as usize) as usize,
                );
            }
        }
    }
    if indices.is_empty() {
        return false;
    }
    // Reject invalid inputs before invoking the generator; unused parent slots
    // neither supply input nor count as failed leaf proof.
    for &index in &indices {
        let position = view.position(index);
        let normal = decode_oct_snorm16(view.normal(index));
        let uv = decode_uv_unorm16(view.uv(index), view.uv_min, view.uv_scale);
        if !position
            .iter()
            .chain(normal.iter())
            .chain(uv.iter())
            .all(|value| value.is_finite())
        {
            return false;
        }
    }
    let mut geometry = LeafGeometry {
        view,
        indices,
        set,
        usable: true,
        visited: 0,
    };
    let succeeded = bevy_mikktspace::generate_tangents(&mut geometry).is_ok();
    succeeded && geometry.usable && geometry.visited == geometry.indices.len()
}

struct LeafGeometry<'a, 'b, F> {
    view: &'a MclView<'b>,
    indices: Vec<usize>,
    set: F,
    usable: bool,
    visited: usize,
}

impl<F: FnMut(usize, [f32; 4])> bevy_mikktspace::Geometry for LeafGeometry<'_, '_, F> {
    fn num_faces(&self) -> usize {
        self.indices.len() / 3
    }
    fn num_vertices_of_face(&self, _: usize) -> usize {
        3
    }
    fn position(&self, face: usize, vertex: usize) -> [f32; 3] {
        self.view.position(self.indices[face * 3 + vertex])
    }
    fn normal(&self, face: usize, vertex: usize) -> [f32; 3] {
        decode_oct_snorm16(self.view.normal(self.indices[face * 3 + vertex]))
    }
    fn tex_coord(&self, face: usize, vertex: usize) -> [f32; 2] {
        decode_uv_unorm16(
            self.view.uv(self.indices[face * 3 + vertex]),
            self.view.uv_min,
            self.view.uv_scale,
        )
    }
    fn set_tangent(
        &mut self,
        tangent: Option<bevy_mikktspace::TangentSpace>,
        face: usize,
        vertex: usize,
    ) {
        self.visited += 1;
        let mut encoded = match tangent {
            Some(tangent) => tangent.tangent_encoded(),
            None => {
                self.usable = false;
                [0.0; 4]
            }
        };
        self.usable &= encoded.iter().all(|value| value.is_finite())
            && encoded[..3].iter().any(|value| *value != 0.0);
        // Bevy uses the opposite handedness from MikkTSpace's encoded sign.
        encoded[3] = -encoded[3];
        (self.set)(self.indices[face * 3 + vertex], encoded);
    }
}
