SCRIPT = Path(__file__).with_name('inspect_skyrim_gpu_capture.py')
SPEC = importlib.util.spec_from_file_location('inspect_skyrim_gpu_capture', SCRIPT)
GPU = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(GPU)


class Format:
    compCount, compByteWidth, compType, type = 4, 4, 'Float', 'Regular'

    def Name(self):
        return 'R32G32B32A32_FLOAT'

    def BGRAOrder(self):
        return False

    def SRGBCorrected(self):
        return False


def texture(**overrides):
    values = dict(resourceId='Texture1', format=Format(), width=2, height=2, depth=1,
                  dimension=2, mips=2, arraysize=1, msSamp=1, byteSize=80,
                  type='Texture2D', creationFlags='ShaderRead')
    return NS(**(values | overrides))


def descriptor(rid='Texture1', **overrides):
    values = dict(resource=rid, secondary='Null', view='View1', type='ReadOnlyImage',
                  flags=0, format=Format(), byteOffset=0, byteSize=0, elementByteSize=0,
                  firstMip=0, numMips=1, firstSlice=0, numSlices=1, minLODClamp=0,
                  textureType='Texture2D',
                  swizzle=NS(red='Red', green='Green', blue='Blue', alpha='Alpha'))
    return NS(**(values | overrides))


def action(event, flags=1, children=()):
    return NS(eventId=event, flags=flags, children=list(children),
              GetName=lambda _: f'event {event}', numIndices=3, numInstances=1,
              dispatchDimension=[0, 0, 0])


def access(index=0):
    return NS(stage='Pixel', type='ReadOnlyImage', index=index, arrayElement=0,
              descriptorStore='Store1', byteOffset=4, byteSize=4, staticallyUnused=False)


class FakeController:
    def __init__(self):
        self.events, self.closed, self.disassemblies = [], False, []
        self.reflection = NS(rawBytes=b'spirv fixture', encoding='SPIRV', constantBlocks=[],
                             readOnlyResources=[NS(name='bound', fixedBindNumber=7,
                                                   fixedBindSetOrSpace=2)],
                             readWriteResources=[], samplers=[], inputSignature=[],
                             outputSignature=[NS(varName='o0', regIndex=0, compCount=4)])

    def GetAPIProperties(self):
        return NS(pipelineType='Vulkan', localRenderer='Vulkan', degraded=False)

    def GetTextures(self):
        return [texture()]

    def GetResources(self):
        return [NS(resourceId='Shader9', name='DXVK shader fixture',
                   autogeneratedName=False, type='Shader'),
                NS(resourceId='Buffer1', name='Buffer device address fixture',
                   autogeneratedName=False, type='Buffer')]

    def GetBuffers(self):
        return [NS(resourceId='Buffer1', length=4096, gpuAddress=0x10001000,
                   creationFlags='Constants')]

    def GetRootActions(self):
        return [action(1, flags=0, children=[action(2), action(3), action(4, flags=0)])]

    def GetStructuredFile(self):
        return None

    def SetFrameEvent(self, event, force):
        self.events.append(event)

    def GetPipelineState(self):
        return self

    def GetVulkanPipelineState(self):
        return NS(pushconsts=struct.pack('<QQ', 0x10001000, 0x10001200))

    def GetViewport(self, index):
        return NS(x=0, y=1080, width=1920, height=-1080, minDepth=0, maxDepth=1, enabled=True)

    def GetScissor(self, index):
        return NS(x=0, y=0, width=1920, height=1080, enabled=True)

    def GetShaderReflection(self, stage):
        return self.reflection if stage == 'Pixel' else None

    def GetShader(self, stage):
        return 'Shader9'

    def GetShaderEntryPoint(self, stage):
        return 'main'

    def GetGraphicsPipelineObject(self):
        return 'GraphicsPipeline1'

    def GetComputePipelineObject(self):
        return 'ComputePipeline2'

    def DisassembleShader(self, pipeline, reflection, target):
        self.disassemblies.append((pipeline, reflection, target))
        return 'OpDecorate %sampled DescriptorSet 0\nOpDecorate %sampled Binding 7\n'

    def GetConstantBlocks(self, stage, only_used):
        return []

    def GetReadOnlyResources(self, stage, only_used):
        return [NS(access=access(), descriptor=descriptor())]

    def GetReadWriteResources(self, stage, only_used):
        return []

    def GetSamplers(self, stage, only_used):
        return []

    def GetOutputTargets(self):
        return [descriptor()]

    def GetDepthTarget(self):
        return descriptor('Null')

    def GetColorBlends(self):
        return []

    def GetTextureData(self, rid, sub):
        return struct.pack('<16f', *range(16))

    def Shutdown(self):
        self.closed = True


class FakeRenderDoc:
    ResultCode = NS(Succeeded=0)
    ShaderStage = NS(Vertex='Vertex', Pixel='Pixel', Compute='Compute')
    ActionFlags = NS(Drawcall=1, Dispatch=2)
    GlobalEnvironment = NS
    ReplayOptions = NS
    Subresource = NS

    def __init__(self):
        self.controller = FakeController()
        self.cap_closed = self.replay_closed = False
        self.open_result = 0

    def GetVersionString(self):
        return '1.45 fake'

    def InitialiseReplay(self, env, args):
        pass

    def OpenCaptureFile(self):
        return NS(OpenFile=lambda *args: self.open_result,
                  LocalReplaySupport=lambda: True,
                  OpenCapture=lambda *args: (0, self.controller),
                  Shutdown=lambda: setattr(self, 'cap_closed', True))

    def ShutdownReplay(self):
        self.replay_closed = True


class CollectorTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        self.output = self.root / 'private-evidence'
        self.capture = self.root / 'frame.rdc'
        self.capture.write_bytes(b'fake capture file')

    def test_action_parents_and_order(self):
        result = GPU.flatten_actions([action(1, children=[action(2), action(3)])], None)
        self.assertEqual([row['event_id'] for _, row in result], [1, 2, 3])
        self.assertEqual(result[1][1]['parent_event_ids'], [1])

    def test_cycle_and_excessive_actions_rejected(self):
        cyclic = action(1)
        cyclic.children.append(cyclic)
        with self.assertRaisesRegex(ValueError, 'duplicate'):
            GPU.flatten_actions([cyclic], None)
        with self.assertRaisesRegex(ValueError, 'max-actions'):
            GPU.flatten_actions([action(1), action(2)], None, 1)

    def test_buffer_whole_range_sentinels_and_bounds(self):
        buffer = NS(length=80)
        for size in (0, 0xFFFFFFFFFFFFFFFF):
            self.assertEqual(GPU.buffer_range(descriptor(byteOffset=16, byteSize=size),
                                              buffer, 128), (16, 64))
        with self.assertRaisesRegex(ValueError, 'outside buffer'):
            GPU.buffer_range(descriptor(byteOffset=16, byteSize=80), buffer, 128)
        with self.assertRaisesRegex(ValueError, 'max-resource'):
            GPU.buffer_range(descriptor(byteSize=80), buffer, 32)

    def test_texture_3d_exports_whole_depth_not_slice(self):
        info = GPU.texture_selection(descriptor(firstMip=1, firstSlice=2),
                                      texture(dimension=3, depth=8), 1024)
        self.assertEqual((info['slice'], info['depth']), (0, 4))
        self.assertTrue(info['whole_depth_mip'])

    def test_texture_mip_slice_and_size_guards(self):
        for view in (descriptor(firstMip=2), descriptor(firstSlice=1)):
            with self.assertRaisesRegex(ValueError, 'outside texture'):
                GPU.texture_selection(view, texture(), 1024)
        with self.assertRaisesRegex(ValueError, 'estimate'):
            GPU.texture_selection(descriptor(), texture(width=4096, height=4096), 1024)

    def test_float4_raw_nonfinite_and_partial_row(self):
        result = GPU.float4_storage(struct.pack('<4f', 1, float('nan'), float('inf'), -2) + b'x')
        self.assertEqual(result['binary32_float4'], [[1.0, 'nan', 'inf', -2.0]])
        self.assertEqual(result['trailing_bytes'], 1)
        json.dumps(result, allow_nan=False)

    def test_reflection_index_not_descriptor_byte_offset(self):
        info = GPU.describe_used(NS(access=access(1), descriptor=descriptor()),
                                  [NS(name='wrong'), NS(name='correct', fixedBindNumber=17)],
                                  {'Texture1': texture()}, {})
        self.assertEqual(info['reflection']['name'], 'correct')
        self.assertEqual(info['reflection']['fixedBindNumber'], 17)
        self.assertEqual(info['descriptor']['swizzle']['red'], 'Red')

    def test_writer_hash_budget_and_no_overwrite(self):
        self.output.mkdir()
        writer = GPU.ArtifactWriter(self.output, 16, 20, 2)
        info = writer.write('raw.bin', b'abcd')
        self.assertEqual(info['sha256'], hashlib.sha256(b'abcd').hexdigest())
        with self.assertRaises(FileExistsError):
            writer.write('raw.bin', b'efgh')
        with self.assertRaisesRegex(ValueError, 'max-resource'):
            writer.reserve(17)
        writer.write('other.bin', b'5678')
        with self.assertRaisesRegex(ValueError, 'max-resources'):
            writer.reserve(1)

    def test_truncated_buffer_read_not_written(self):
        self.output.mkdir()
        writer = GPU.ArtifactWriter(self.output, 1024, 2048, 10)
        controller = NS(GetBufferData=lambda *args: b'short')
        with self.assertRaisesRegex(ValueError, 'truncated'):
            GPU.export_descriptor(None, controller, descriptor('Buffer1', byteSize=64),
                                   {}, {'Buffer1': NS(length=64)}, writer, 'bad', False)
        self.assertEqual(writer.files, [])

    def test_collect_tail_metadata_has_no_resource_exports(self):
        rd = FakeRenderDoc()
        result = GPU.collect(rd, self.capture, self.output, tail=1)
        self.assertEqual(rd.controller.events, [3])
        self.assertEqual(result['status'], 'complete')
        self.assertEqual(result['artifacts'], [])
        self.assertEqual(result['capture']['sha256'], result['capture']['sha256_after_replay'])
        self.assertTrue(rd.cap_closed and rd.replay_closed and rd.controller.closed)
        self.assertEqual(result['pipelines'][0]['stages'][0]['read_only'][0]
                         ['reflection']['fixedBindNumber'], 7)

    def test_selected_event_exports_hashed_raw_not_preview(self):
        rd = FakeRenderDoc()
        result = GPU.collect(rd, self.capture, self.output, events=[2], tail=0)
        self.assertEqual(rd.controller.events, [2])
        self.assertEqual(len(result['artifacts']), 5)
        for file in result['artifacts']:
            self.assertEqual(GPU.sha256_file(self.output / file['path']), file['sha256'])
        exported = result['pipelines'][0]['stages'][0]['read_only'][0]['export']
        self.assertEqual(exported['selection']['sample'], 0)
        self.assertNotIn('preview', exported)

    def test_graphics_disassembly_hash_and_negative_viewport_preserved(self):
        rd = FakeRenderDoc()
        result = GPU.collect(rd, self.capture, self.output, events=[2], tail=0)
        event = result['pipelines'][0]
        disassembly = event['stages'][0]['disassembly']
        self.assertEqual(rd.controller.disassemblies[0][0], 'GraphicsPipeline1')
        self.assertEqual(rd.controller.disassemblies[0][2], '')
        self.assertIn('Binding 7', (self.output / disassembly['path']).read_text())
        self.assertEqual(event['viewport_0']['height'], -1080)
        self.assertEqual(event['stages'][0]['outputSignature'][0]['compCount'], 4)
        self.assertEqual(result['resources'][0]['name'], 'DXVK shader fixture')

    def test_compute_disassembly_selects_compute_pipeline(self):
        rd = FakeRenderDoc()
        rd.controller.GetShaderReflection = lambda stage: (
            rd.controller.reflection if stage == 'Compute' else None)
        rd.controller.GetRootActions = lambda: [action(2, flags=2)]
        GPU.collect(rd, self.capture, self.output, events=[2], tail=0)
        self.assertEqual(rd.controller.disassemblies[0][0], 'ComputePipeline2')

    def test_draw_ignores_stale_compute_binding_and_dispatch_ignores_graphics(self):
        rd = FakeRenderDoc()
        rd.controller.GetShaderReflection = lambda stage: rd.controller.reflection
        result = GPU.collect(rd, self.capture, self.output, tail=1)
        self.assertEqual(result['pipelines'][0]['pipeline_scope'], 'graphics')
        self.assertEqual([stage['stage'] for stage in result['pipelines'][0]['stages']],
                         ['Vertex', 'Pixel'])
        rd.controller.GetRootActions = lambda: [action(2, flags=2)]
        result = GPU.collect(rd, self.capture, self.root / 'dispatch-evidence', tail=1)
        self.assertEqual(result['pipelines'][0]['pipeline_scope'], 'compute')
        self.assertEqual([stage['stage'] for stage in result['pipelines'][0]['stages']], ['Compute'])
        self.assertEqual(result['pipelines'][0]['outputs'], [])
        self.assertNotIn('viewport_0', result['pipelines'][0])

    def test_shader_debug_filename_and_spirv_source_key_are_correlation_only(self):
        name = 'fs.716590ec34046095c58617804cdff8cc'
        literal = name.encode() + b'\0'
        literal += b'\0' * (-len(literal) % 4)
        instruction = struct.pack('<II', ((2 + len(literal) // 4) << 16) | 7, 9) + literal
        header = struct.pack('<5I', 0x07230203, 0x10000, 0, 10, 0)
        reflection = NS(debugInfo=NS(files=[NS(filename=f'/private/shaders/{name}')]))
        result = GPU.shader_source_metadata(reflection, header + instruction)
        self.assertEqual(result['debug_source_files'], [f'/private/shaders/{name}'])
        self.assertEqual([candidate['name'] for candidate in result['shader_name_candidates']],
                         [name, name])
        self.assertEqual(result['shader_name_candidates'][1]['instruction_word_offset'], 5)
        self.assertEqual(result['spirv_source_scan'], 'parsed-source-strings')

    def test_malformed_spirv_instruction_does_not_loop_or_claim_source_key(self):
        header = struct.pack('<5I', 0x07230203, 0x10000, 0, 10, 0)
        result = GPU.shader_source_metadata(NS(), header + b'\0\0\0\0')
        self.assertEqual(result['shader_name_candidates'], [])
        self.assertEqual(result['spirv_source_scan'], 'malformed-instruction-length')

    def test_push_constants_and_buffer_address_inventory_without_buffer_dump(self):
        rd = FakeRenderDoc()
        result = GPU.collect(rd, self.capture, self.output, events=[2], tail=0)
        push = result['pipelines'][0]['vulkan_push_constants']
        expected = struct.pack('<QQ', 0x10001000, 0x10001200)
        self.assertEqual(push['hex'], expected.hex())
        self.assertEqual((self.output / push['raw']['path']).read_bytes(), expected)
        self.assertEqual(result['buffers'][0]['gpuAddress'], 0x10001000)
        self.assertEqual(result['buffers'][0]['gpu_address_hex'], '0x10001000')
        self.assertEqual(result['buffers'][0]['resource_name'], 'Buffer device address fixture')
        self.assertEqual(result['buffers'][0]['length'], 4096)
        # FakeController intentionally has no GetBufferData method. Successful
        # inspection proves inventory did not blindly fetch these buffer bytes.

    def test_non_vulkan_selected_event_omits_push_constants(self):
        rd = FakeRenderDoc()
        rd.controller.GetVulkanPipelineState = lambda: None
        result = GPU.collect(rd, self.capture, self.output, events=[2], tail=0)
        self.assertNotIn('vulkan_push_constants', result['pipelines'][0])

    def test_failed_open_writes_failure_receipt_and_closes(self):
        rd = FakeRenderDoc()
        rd.open_result = 99
        with self.assertRaisesRegex(ValueError, 'Capture open failed'):
            GPU.collect(rd, self.capture, self.output)
        receipt = json.loads((self.output / 'receipt.json').read_text())
        self.assertEqual(receipt['status'], 'failed')
        self.assertTrue(rd.cap_closed and rd.replay_closed)
        self.assertFalse(rd.controller.closed)

    def test_selected_event_must_be_draw_or_dispatch(self):
        with self.assertRaisesRegex(ValueError, 'draw or dispatch'):
            GPU.collect(FakeRenderDoc(), self.capture, self.output, events=[4])
        self.assertEqual(json.loads((self.output / 'receipt.json').read_text())['status'], 'failed')

    def test_existing_output_and_duplicate_events_rejected_before_replay(self):
        rd = FakeRenderDoc()
        with self.assertRaisesRegex(ValueError, 'Duplicate'):
            GPU.collect(rd, self.capture, self.output, events=[2, 2])
        self.output.mkdir()
        with self.assertRaisesRegex(ValueError, 'already exists'):
            GPU.collect(rd, self.capture, self.output)
        self.assertFalse(rd.replay_closed)


if __name__ == '__main__':
    unittest.main()
